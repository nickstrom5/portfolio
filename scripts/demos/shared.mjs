export const targets = { portfolio, launchneat };
export let target = portfolio;
export const setTarget = (name) => {
  if (!targets[name]) throw new Error(`Unknown target "${name}". Use one of: ${Object.keys(targets).join(', ')}`);
  target = targets[name];
};

export const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');

/** <head> for a concept-site page. Concept sites are noindex and use their own fonts and CSS. */
export function head({ slug, title, desc, path, fonts, css, theme, icon }) {
  const fontLinks = target.selfHostFonts
    ? `<link rel="stylesheet" href="/demos/fonts/${slug}.css">`
    : `<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="${fonts}">`;
  return `<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${esc(desc)}">
<meta name="robots" content="noindex, follow">
<link rel="canonical" href="${target.origin}${path}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta name="theme-color" content="${theme}">
<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(icon)}">
${fontLinks}
<link rel="stylesheet" href="${css}">${target.extraHead}
<script src="/demos/site.js" defer></script>`;
}

/** The line every concept site carries in its footer. */
export const conceptNote = (name) => target.credit(name);

